using Xunit;

// Тесты идут строго по одному. Stryker определяет, какие тесты затрагивают какой кусок кода, наблюдая
// за прогоном; если тесты идут вперемешку, эти наблюдения путаются между тестами, и мутанты
// проверялись бы не теми тестами. Платой за точность становится скорость, зато каждый мутант
// потом проверяется только теми тестами, которые его касаются.
[assembly: CollectionBehavior(DisableTestParallelization = true)]
